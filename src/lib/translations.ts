export function translate(language: Language, text: string) {
  if (language === "en") return text;
  const trimmed = text.trim();
  const translated =
    language === "my"
      ? myanmar[trimmed]
      : uiTranslations[trimmed]?.[language] ??
        additionalTranslations[language]?.[trimmed];
  return translated ? text.replace(trimmed, translated) : text;
}
